-- CSPD201TM / CSPD202TM 누락 컬럼 추가
-- 컬럼: TRN_OPR_NO, INPT_ATMC_BIZ_DSCD, KRBR_NM, DACC_BRCD, CUS_ENG_NM
-- 추가 컬럼(XPO_PTN_NACD/XPO_NACD/HS_CD)은 24_cspd201_202_hs_nacd_fix.sql 참고
-- 원인: RevertUngenerated / RevertStatAll / RevertStatComplete /
--       TaskLogEnd / StatItem / StatCond / StatUser 등 MyBatis에서 원장(201/202) 컬럼 참조
--
-- 실행: 기존 DB에 CSPD201TM/CSPD202TM이 이미 생성된 경우 1회 실행
--       신규 설치(01_ddl 수정본) 시 불필요
--       이미 추가된 컬럼은 ORA-01430 등으로 무시 후 다음 문장 진행
-- ============================================================

ALTER TABLE CSPD201TM ADD TRN_OPR_NO VARCHAR2(64);
ALTER TABLE CSPD201TM ADD INPT_ATMC_BIZ_DSCD VARCHAR2(32);
ALTER TABLE CSPD201TM ADD KRBR_NM VARCHAR2(300);
ALTER TABLE CSPD201TM ADD DACC_BRCD VARCHAR2(32);
ALTER TABLE CSPD201TM ADD CUS_ENG_NM VARCHAR2(300);

COMMENT ON COLUMN CSPD201TM.TRN_OPR_NO IS '조작자 사번';
COMMENT ON COLUMN CSPD201TM.INPT_ATMC_BIZ_DSCD IS '심사 자동화 업무 구분 코드';
COMMENT ON COLUMN CSPD201TM.KRBR_NM IS '영업점명';
COMMENT ON COLUMN CSPD201TM.DACC_BRCD IS '일계점코드(영업점코드)';
COMMENT ON COLUMN CSPD201TM.CUS_ENG_NM IS '고객 영문명';

ALTER TABLE CSPD202TM ADD TRN_OPR_NO VARCHAR2(64);
ALTER TABLE CSPD202TM ADD INPT_ATMC_BIZ_DSCD VARCHAR2(32);
ALTER TABLE CSPD202TM ADD KRBR_NM VARCHAR2(300);
ALTER TABLE CSPD202TM ADD DACC_BRCD VARCHAR2(32);
ALTER TABLE CSPD202TM ADD CUS_ENG_NM VARCHAR2(300);

COMMENT ON COLUMN CSPD202TM.TRN_OPR_NO IS '조작자 사번';
COMMENT ON COLUMN CSPD202TM.INPT_ATMC_BIZ_DSCD IS '심사 자동화 업무 구분 코드';
COMMENT ON COLUMN CSPD202TM.KRBR_NM IS '영업점명';
COMMENT ON COLUMN CSPD202TM.DACC_BRCD IS '일계점코드(영업점코드)';
COMMENT ON COLUMN CSPD202TM.CUS_ENG_NM IS '고객 영문명';

-- 테스트 원장 보정 (수출=1, 수입=2)
UPDATE CSPD201TM
   SET TRN_OPR_NO = NVL(TRN_OPR_NO, 'E10001'),
       INPT_ATMC_BIZ_DSCD = NVL(INPT_ATMC_BIZ_DSCD, '1'),
       KRBR_NM = NVL(KRBR_NM, '본점'),
       DACC_BRCD = NVL(DACC_BRCD, '0001'),
       CUS_ENG_NM = NVL(CUS_ENG_NM, CASE XPO_CVRG_MK_SQ
         WHEN 1 THEN 'TEST EXPORT CO LTD'
         WHEN 2 THEN 'GLOBAL TRADE'
         ELSE CUS_ENG_NM END)
 WHERE XPO_CVRG_MK_SQ IN (1, 2);

UPDATE CSPD202TM
   SET TRN_OPR_NO = NVL(TRN_OPR_NO, 'E10001'),
       INPT_ATMC_BIZ_DSCD = NVL(INPT_ATMC_BIZ_DSCD, '2'),
       KRBR_NM = NVL(KRBR_NM, '본점'),
       DACC_BRCD = NVL(DACC_BRCD, '0001'),
       CUS_ENG_NM = NVL(CUS_ENG_NM, CASE TDOC_RCP_SRNO
         WHEN 1 THEN 'TEST EXPORT CO LTD'
         WHEN 2 THEN 'KOREA IMPORT TRADING'
         ELSE CUS_ENG_NM END)
 WHERE TDOC_RCP_SRNO IN (1, 2);

COMMIT;
