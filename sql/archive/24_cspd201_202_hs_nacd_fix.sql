-- ============================================================
-- CSPD201TM / CSPD202TM 누락 컬럼 추가 (통계 원장 조회용)
-- 컬럼:
--   CSPD201TM: XPO_PTN_NACD, HS_CD
--   CSPD202TM: XPO_NACD, HS_CD
-- 원인: StatItem / StatCond / CommonSanctionStat MyBatis에서
--       수출상대국코드·HS코드 컬럼 참조
--
-- 실행: 기존 DB에 CSPD201TM/CSPD202TM이 이미 생성된 경우 1회 실행
--       신규 설치(01_ddl 수정본) 시 불필요
--       이미 추가된 컬럼은 ORA-01430 등으로 무시 후 다음 문장 진행
-- ============================================================

ALTER TABLE CSPD201TM ADD XPO_PTN_NACD VARCHAR2(32);
ALTER TABLE CSPD201TM ADD HS_CD VARCHAR2(32);

COMMENT ON COLUMN CSPD201TM.XPO_PTN_NACD IS '수출상대국코드';
COMMENT ON COLUMN CSPD201TM.HS_CD IS 'HS코드';

ALTER TABLE CSPD202TM ADD XPO_NACD VARCHAR2(32);
ALTER TABLE CSPD202TM ADD HS_CD VARCHAR2(32);

COMMENT ON COLUMN CSPD202TM.XPO_NACD IS '수출상대국코드';
COMMENT ON COLUMN CSPD202TM.HS_CD IS 'HS코드';

-- 테스트 원장 보정
UPDATE CSPD201TM
   SET XPO_PTN_NACD = NVL(XPO_PTN_NACD, CASE XPO_CVRG_MK_SQ WHEN 1 THEN 'US' WHEN 2 THEN 'CN' ELSE XPO_PTN_NACD END),
       HS_CD = NVL(HS_CD, CASE XPO_CVRG_MK_SQ WHEN 1 THEN '847130' WHEN 2 THEN '870323' ELSE HS_CD END)
 WHERE XPO_CVRG_MK_SQ IN (1, 2);

UPDATE CSPD202TM
   SET XPO_NACD = NVL(XPO_NACD, CASE TDOC_RCP_SRNO WHEN 1 THEN 'US' WHEN 2 THEN 'CN' ELSE XPO_NACD END),
       HS_CD = NVL(HS_CD, CASE TDOC_RCP_SRNO WHEN 1 THEN '847130' WHEN 2 THEN '870323' ELSE HS_CD END)
 WHERE TDOC_RCP_SRNO IN (1, 2);

COMMIT;
